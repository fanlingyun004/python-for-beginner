# 中文翻译：以上英文文档字符串用于说明对象的用途、输入和输出。


def square(n):
    """Return n squared."""
    # 中文翻译：以上英文文档字符串用于说明对象的用途、输入和输出。
    return n * n


def cube(n):
    """Return n cubed."""
    # 中文翻译：以上英文文档字符串用于说明对象的用途、输入和输出。
    return n ** 3


def is_even(n):
    """Return True if n is even."""
    # 中文翻译：以上英文文档字符串用于说明对象的用途、输入和输出。
    return n % 2 == 0
